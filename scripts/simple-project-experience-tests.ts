assert.match(meProjects, /<h1[^>]*>我的项目<\/h1>/, "project list should use the simple user-facing title");
assert.match(meProjects, /从想法到第一件真实产品/, "project list should explain the journey in plain language");
assert.match(meProjects, /新建项目/, "project list should keep one clear creation entry");
assert.match(meProjects, /StageProgress/, "project list should show the four-stage progress UI");
assert.match(meProjects, /继续/, "project cards should expose one primary continue action");
