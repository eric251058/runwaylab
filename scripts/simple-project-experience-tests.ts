assert.match(projectDetail, /StageProgress/, "project detail should show lightweight stage progress");
assert.match(projectDetail, /PrivateProjectActionCard/, "project detail should keep the real user action workflow");
assert.doesNotMatch(projectDetail, /当前动作|当前行动|正式项目|原始启动|责任方|事件模型/, "project detail should avoid internal project-management language");
assert.match(actionCard, /现在要做/, "USER active detail state should say what to do now");
assert.match(actionCard, /已收到/, "submitted user result should show a received state");
assert.match(actionCard, /我们正在处理/, "platform-owned action should be hidden behind a processing state");
